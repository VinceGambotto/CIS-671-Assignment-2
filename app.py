def find_database():
    env = os.environ.get("WILDFIRE_DB")
    if env and Path(env).exists():
        return Path(env)
    for p in HERE.glob("*.sqlite"):
        return p
    import kagglehub  # only needed when the data is not already on disk

    folder = Path(kagglehub.dataset_download("rtatman/188-million-us-wildfires"))
    p = folder / DB_NAME
    if p.exists():
        return p
    found = list(folder.rglob("*.sqlite"))
    if found:
        return found[0]
    raise FileNotFoundError(f"No .sqlite file found in {folder}")


@st.cache_data(show_spinner="Reading the wildfire database (this is slow only the first time)...")
def load_summary():
    """Returns rows of [year, size_class, number_of_fires, acres_burned] for 1992-2015."""
    if CACHE_FILE.exists():
        try:
            rows = json.loads(CACHE_FILE.read_text(encoding="utf-8"))
            if rows:
                return rows
        except Exception:
            pass
    con = sqlite3.connect(str(find_database()))
    try:
        df = pd.read_sql_query(
            "SELECT FIRE_YEAR, FIRE_SIZE_CLASS, COUNT(*) AS fires, SUM(FIRE_SIZE) AS acres "
            "FROM Fires WHERE FIRE_YEAR BETWEEN 1992 AND 2015 "
            "GROUP BY FIRE_YEAR, FIRE_SIZE_CLASS",
            con,
        )
    finally:
        con.close()
    df["FIRE_YEAR"] = df["FIRE_YEAR"].astype(int)
    df["fires"] = df["fires"].astype(int)
    df["acres"] = df["acres"].astype(float)
    df["FIRE_SIZE_CLASS"] = df["FIRE_SIZE_CLASS"].where(df["FIRE_SIZE_CLASS"].notna(), None)
    rows = df.values.tolist()
    try:
        CACHE_FILE.write_text(json.dumps(rows), encoding="utf-8")
    except Exception:
        pass  # a read-only folder is fine; the app just reads the database again next time
    return rows


